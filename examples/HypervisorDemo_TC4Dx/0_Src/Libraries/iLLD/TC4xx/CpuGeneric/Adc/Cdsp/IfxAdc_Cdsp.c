IfxAdc_Cdsp_CoreResult IfxAdc_Cdsp_readResult0(IfxAdc_Cdsp_Core *dsp)
{
    IfxAdc_Cdsp_CoreResult result = { .result = 0, .timestamp = 0u, .timestampValid = FALSE };
    if (IfxAdc_getCdspResultEvent(dsp->cdspSFR, dsp->coreId, IfxAdc_CdspResultReg_0))
    {
        uint32 rawVal = IfxAdc_Cdsp_readResult0Raw(dsp);
        result.result = IfxAdc_Cdsp_lDecodeResult(rawVal, dsp->resultCfg.enableTimestamp,
            dsp->resultCfg.readAsUnsigned);
        if (dsp->resultCfg.enableTimestamp)
        {
            if (dsp->dspSFR->TSTMP.B.TSVAL != 0u)
            {
                result.timestamp = (uint16)(rawVal >> IFX_ADC_CDSP_DSP_RES_CRESULTHI_OFF);
                result.timestampValid = TRUE;
            }
        }
        IfxAdc_clearCdspResultEvent(dsp->cdspSFR, dsp->coreId, IfxAdc_CdspResultReg_0);
    }
    return result;
}

uint8 IfxAdc_Cdsp_readFifo(IfxAdc_Cdsp_Core *dsp, uint16 *buf, uint8 maxCount)
{
    uint8 written = 0u;
    if ((maxCount == 0u) || (buf == NULL_PTR))
    {
        return written;
    }
    if (IfxAdc_getCdspResultEvent(dsp->cdspSFR, dsp->coreId, IfxAdc_CdspResultReg_0))
    {
        uint8 fillLevel = IfxAdc_Cdsp_getFifoFillLevel(dsp);
        boolean dr32 = (dsp->resultCfg.dataReadWidth == IfxAdc_CdspDataReadWidth_32Bit);
        while (written < fillLevel)
        {
            uint8 halfwords = 1u;
            if (dr32 && ((uint8)(fillLevel - written) > 1u))
            {
                halfwords = 2u;
            }
            if ((uint8)(maxCount - written) < halfwords)
            {
                break;
            }
            uint32 rawVal = IfxAdc_Cdsp_readResult0Raw(dsp);
            buf[written] = (uint16)rawVal;
            written++;
            if (halfwords == 2u)
            {
                buf[written] = (uint16)(rawVal >> IFX_ADC_CDSP_DSP_RES_CRESULTHI_OFF);
                written++;
            }
        }
        if ((written != 0u) && (written == fillLevel))
        {
            IfxAdc_clearCdspResultEvent(dsp->cdspSFR, dsp->coreId, IfxAdc_CdspResultReg_0);
        }
    }
    return written;
}

