        IfxAdc_Cdsp_Core core;
        core.dspSFR = dsp->dspSFR;
        resultPtr->angularVelocity = (float32)((IfxAdc_Cdsp_readResult0Raw(&core)) * (float32)(0.00001));
        resultPtr->estimatedAngle  = (float32)((IfxAdc_Cdsp_readResult1Raw(&core)) * (float32)(0.00001));
