void IfxAdc_Cdsp_updateInputAddress(IfxAdc_CdspInput inputsel, uint32 *dccmAddr)
{
    volatile uint32 *dccmInAddress = dccmAddr;

    if(dccmInAddress != NULL_PTR)
    {
        if(inputsel <= IfxAdc_CdspInput_dsadc9)
        {
            /*Dsadc*/
            *dccmInAddress =  ((uint32)(0x9010) + (4*(inputsel)));

        }
        else if(inputsel >= IfxAdc_CdspInput_exmod0  && inputsel <= IfxAdc_CdspInput_exmod7)
        {
            /*exmod*/
            *dccmInAddress =  ((uint32)(0x9048) + (4*(inputsel - IfxAdc_CdspInput_exmod0)));

        }
        else if(inputsel == IfxAdc_CdspInput_carmag)
        {
            /** Carrier */
            *dccmInAddress =  ((uint32)(0x9068));

        }
        else if(inputsel >= IfxAdc_CdspInput_tmadc0Res0 && inputsel <= IfxAdc_CdspInput_tmadc6Res5)
        {
            /** Tmadc */
            if(inputsel >= IfxAdc_CdspInput_tmadc0Res0 && inputsel <= IfxAdc_CdspInput_tmadc6Res1)
            {
                uint8 v = ((inputsel - IfxAdc_CdspInput_tmadc0Res0) %  (2u)); 
                uint8 x  = (inputsel - IfxAdc_CdspInput_tmadc0Res0) / (2u); 
                *dccmInAddress =  (((uint32)(0x906C)) + (4*((2*x)+v)));
            }
            else if(inputsel >= IfxAdc_CdspInput_tmadc0Res2 && inputsel <= IfxAdc_CdspInput_tmadc6Res3)
            {
                uint8 v = ((inputsel - IfxAdc_CdspInput_tmadc0Res2) %  (2u)) + (2u); 
                uint8 x  = (inputsel - IfxAdc_CdspInput_tmadc0Res2) / (2u); 
                *dccmInAddress =  (((uint32)(0x90AC)) + (4*((2*x)+v)));
            }
            else
            {
                uint8 v = ((inputsel - IfxAdc_CdspInput_tmadc0Res4) %  (2u)) + (4u); 
                uint8 x  = (inputsel - IfxAdc_CdspInput_tmadc0Res4) / (2u); 
                *dccmInAddress =  (((uint32)(0x90EC)) + (4*((2*x)+v)));
            }

        }
        else if(inputsel >= IfxAdc_CdspInput_auxdsadc0 && inputsel <= IfxAdc_CdspInput_auxdsadc9)
        {
            /*Dsadc*/
            *dccmInAddress =  ((uint32)(0x9290) + (4*(inputsel - IfxAdc_CdspInput_dsadc0)));

        }
        else if(inputsel >= IfxAdc_CdspInput_auxexmod0 && inputsel <= IfxAdc_CdspInput_auxexmod7)
        {
            /*exmod*/
            *dccmInAddress =  ((uint32)(0x92C8) + (4*(inputsel - IfxAdc_CdspInput_exmod0)));

        }
        else if(inputsel >= IfxAdc_CdspInput_gp0 && inputsel <= IfxAdc_CdspInput_gp3)
        {
            *dccmInAddress =  ((uint32)(0x9400) + (4*(inputsel - IfxAdc_CdspInput_gp0)));
        }
        else 
        {
            *dccmInAddress = 0u; 
        }
    }
}

