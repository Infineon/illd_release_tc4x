IfxAdc_Status IfxAdc_Cdsp_loadImageFromFlash(IfxAdc_CdspCore coreId,
    uint32 flashBase, uint32 imageIndex)
{
    uint32 slotBase;
    if (!IfxAdc_Cdsp_lIsCoreValid(coreId) || (flashBase == 0u) || ((flashBase & 0x3u) != 0u))
    {
        return IfxAdc_Status_failure;
    }
    if (imageIndex > ((0xFFFFFFFFu - flashBase) / IFXADC_CDSP_IMAGE_STRIDE))
    {
        return IfxAdc_Status_failure;
    }
    slotBase = flashBase + (imageIndex * IFXADC_CDSP_IMAGE_STRIDE);
    if (slotBase > (0xFFFFFFFFu - (IFXADC_CDSP_IMAGE_STRIDE - 1u)))
    {
        return IfxAdc_Status_failure;
    }
    if ((ADC_CDSP_DSP0_ICCM_SIZE > 0xFFFFu) || (ADC_CDSP_DSP0_DCCM_SIZE > 0xFFFFu))
    {
        return IfxAdc_Status_failure;
    }
    if (!IfxAdc_Cdsp_lIsImageValid((const void *)slotBase,
            (uint16)ADC_CDSP_DSP0_ICCM_SIZE, ADC_CDSP_DSP0_ICCM_SIZE) ||
        !IfxAdc_Cdsp_lIsImageValid((const void *)(slotBase + ADC_CDSP_DSP0_ICCM_SIZE),
            (uint16)ADC_CDSP_DSP0_DCCM_SIZE, ADC_CDSP_DSP0_DCCM_SIZE))
    {
        return IfxAdc_Status_failure;
    }
    IfxAdc_Cdsp_loadIccm(coreId, (const void *)slotBase, (uint16)ADC_CDSP_DSP0_ICCM_SIZE);
    IfxAdc_Cdsp_loadDccm(coreId, (const void *)(slotBase + ADC_CDSP_DSP0_ICCM_SIZE),
        (uint16)ADC_CDSP_DSP0_DCCM_SIZE);
#if IFXADC_CDSP_SW_BREAKPOINTS
    IfxAdc_Cdsp_lInjectSwBreakpoints(coreId);
#endif
    return IfxAdc_Status_success;
}

IfxAdc_Status IfxAdc_Cdsp_loadFromArray(IfxAdc_CdspCore coreId,
    const void *iccmSrc, uint16 iccmSize, const void *dccmSrc, uint16 dccmSize)
{
    if (!IfxAdc_Cdsp_lIsCoreValid(coreId) ||
        !IfxAdc_Cdsp_lIsImageValid(iccmSrc, iccmSize, ADC_CDSP_DSP0_ICCM_SIZE) ||
        !IfxAdc_Cdsp_lIsImageValid(dccmSrc, dccmSize, ADC_CDSP_DSP0_DCCM_SIZE))
    {
        return IfxAdc_Status_failure;
    }
    IfxAdc_Cdsp_clearMemory(coreId);
    IfxAdc_Cdsp_loadIccm(coreId, iccmSrc, iccmSize);
    IfxAdc_Cdsp_loadDccm(coreId, dccmSrc, dccmSize);
#if IFXADC_CDSP_SW_BREAKPOINTS
    IfxAdc_Cdsp_lInjectSwBreakpoints(coreId);
#endif
    return IfxAdc_Status_success;
}

